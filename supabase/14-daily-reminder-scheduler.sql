-- Wimm periodic push scheduler: Supabase Cron + one-time SQL tokens.
-- Keep this versioned migration. Does not touch financial transactions.
-- Supabase Cron runs every 5 minutes and only calls Wimm if a daily reminder is enabled.
-- No shared long-lived password, VAPID private key or CRON_SECRET in the database.
create extension if not exists pg_cron with schema pg_catalog;
create extension if not exists pg_net with schema extensions;

create table if not exists budget_private.push_dispatch_tokens (
  token uuid primary key default gen_random_uuid(),
  expires_at timestamptz not null default now() + interval '2 minutes'
);
alter table budget_private.push_dispatch_tokens enable row level security;
revoke all on budget_private.push_dispatch_tokens from public,anon,authenticated,service_role;

-- Only the Wimm server (Supabase service_role) can consume a 2-minute one-use token.
create or replace function public.budget_push_cron_consume(p_token uuid)
returns boolean language plpgsql volatile security definer set search_path=''
as $$
declare accepted boolean;
begin
  if p_token is null then return false; end if;
  delete from budget_private.push_dispatch_tokens
    where token=p_token and expires_at > now()
    returning true into accepted;
  return coalesce(accepted,false);
end;
$$;
revoke all on function public.budget_push_cron_consume(uuid) from public,anon,authenticated,service_role;
grant execute on function public.budget_push_cron_consume(uuid) to service_role;

-- This internal function is invoked only by postgres' scheduler.
-- The token is generated by the DB, sent directly to Wimm over HTTPS and consumed once.
create or replace function budget_private.push_schedule_tick()
returns void language plpgsql volatile security definer set search_path=''
as $$
declare
  ticket uuid;
  request_id bigint;
begin
  delete from budget_private.push_dispatch_tokens where expires_at < now() - interval '1 hour';
  if not exists(select 1 from budget_private.push_devices where daily_reminder=true) then
    return;
  end if;
  insert into budget_private.push_dispatch_tokens default values returning token into ticket;
  select net.http_get(
    url := 'https://wimm-budget.vercel.app/api/push-cron',
    headers := jsonb_build_object('Authorization','Bearer ' || ticket::text),
    timeout_milliseconds := 30000
  ) into request_id;
end;
$$;
revoke all on function budget_private.push_schedule_tick() from public,anon,authenticated,service_role;

-- Re-running schedule with same name updates the job (no duplicate schedules).
select cron.schedule(
  'wimm-daily-transactions-dispatch',
  '*/5 * * * *',
  'select budget_private.push_schedule_tick()'
);
